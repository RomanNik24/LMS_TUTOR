def _range_map(bounds: tuple[tuple[int, int, int], ...]) -> dict[int, int]:
    """Разворачивает диапазоны «первичные баллы → результат» в словарь.

    Args:
        bounds: кортеж троек ``(начало, конец, результат)`` включительно.

    Returns:
        Словарь ``{primary_score: result_value}`` по всем целым баллам.
    """
    mapping: dict[int, int] = {}
    for start, end, value in bounds:
        for score in range(start, end + 1):
            mapping[score] = value
    return mapping


